def import_majors():
    """导入专业数据到Supabase"""
    print(f"正在导入 {len(majors_data)} 个专业数据...")
    
    success_count = 0
    error_count = 0
    
    for major in majors_data:
        try:
            result = supabase.table('majors').insert(major).execute()
            success_count += 1
            if success_count % 5 == 0:
                print(f"已成功导入 {success_count} 个专业...")
        except Exception as e:
            error_count += 1
            print(f"导入 '{major['name']}' 时出错: {str(e)[:100]}")
            continue
    
    print(f"\n导入完成！成功: {success_count}, 失败: {error_count}")
    return success_count, error_count

