def fetch_existing_majors():
    """获取数据库中现有的专业代码"""
    url = f'{SUPABASE_URL}/rest/v1/majors?select=code'
    req = urllib.request.Request(url)
    req.add_header('apikey', SUPABASE_KEY)
    req.add_header('Authorization', f'Bearer {SUPABASE_KEY}')
    with urllib.request.urlopen(req, context=ctx) as response:
        data = json.loads(response.read().decode('utf-8'))
        return {item['code'] for item in data}

def analyze_gaps():
    """分析缺失的专业"""
    existing = fetch_existing_majors()
    print(f"现有专业数量: {len(existing)}")
    
    total_ministry = 0
    total_missing = 0
    
    print("\n" + "="*60)
    print("教育部2024年本科专业目录覆盖情况分析")
    print("="*60)
    
    for category, majors in sorted(MINISTRY_2024_CATEGORIES.items()):
        total_ministry += len(majors)
        existing_in_cat = sum(1 for code in majors.keys() if code in existing)
        missing_in_cat = [(code, name) for code, name in majors.items() if code not in existing]
        total_missing += len(missing_in_cat)
        
        coverage = existing_in_cat / len(majors) * 100 if len(majors) > 0 else 0
        status = "✅" if coverage == 100 else "⚠️" if coverage > 50 else "❌"
        
        print(f"\n{status} {category}: {existing_in_cat}/{len(majors)} ({coverage:.0f}%)")
        
        if missing_in_cat:
            for code, name in missing_in_cat[:5]:
                print(f"   ❌ {code} {name}")
            if len(missing_in_cat) > 5:
                print(f"   ... 还有 {len(missing_in_cat) - 5} 个")
    
    print("\n" + "="*60)
    print(f"总结: 现有 {len(existing)} 个, 清单共 {total_ministry} 个, 缺失 {total_missing} 个")
    print("="*60)

if __name__ == '__main__':
    analyze_gaps()
