def update_majors():
    print(f"Updating {len(detailed_data)} majors with detailed content...")
    success = 0
    errors = 0
    
    for code, data in detailed_data.items():
        try:
            result = supabase.table('majors').update(data).eq('code', code).execute()
            print(f"✓ {code}")
            success += 1
        except Exception as e:
            print(f"✗ {code}: {e}")
            errors += 1
    
    print(f"\nDone! Success: {success}, Errors: {errors}")

if __name__ == "__main__":
    update_majors()
