    print(f"  数据库现有专业数: {len(db_majors)}")
    
    # 2. 分析对比
    print("\n[步骤2] 分析清单与数据库差异...")
    db_codes = {m['code'] for m in db_majors}
    ministry_codes = set(MINISTRY_MAJORS.keys())
    
    # 查找需要删除的（不在清单中的）
    codes_to_delete = db_codes - ministry_codes
    items_to_delete = [m for m in db_majors if m['code'] in codes_to_delete]
    
    # 查找需要补充的（清单有但数据库没有）
    codes_to_add = ministry_codes - db_codes
    
    print(f"  需删除的专业数: {len(items_to_delete)}")
    print(f"  需补充的专业数: {len(codes_to_add)}")
    
    # 3. 删除不在清单的专业
    if items_to_delete:
        print(f"\n[步骤3] 删除不在教育部清单的 {len(items_to_delete)} 个专业...")
        deleted_count = 0
        for item in items_to_delete[:]:
            print(f"  删除: {item['code']} - {item['name']}")
            if delete_from_db(item['id']):
                deleted_count += 1
                items_to_delete.remove(item)
            time.sleep(0.1)
        print(f"  已删除 {deleted_count} 个专业")
    
    # 4. 检查是否有代码格式问题（比如缺少K/T后缀）
    print(f"\n[步骤4] 检查代码格式匹配问题...")
    format_issues = []
    for m in db_majors:
        if m['code'] not in codes_to_delete:  # 只检查保留的
            code = m['code']
            if len(code) == 6:  # 无后缀
                # 检查可能的带后缀版本
                for suffix in ['K', 'T', 'TK']:
                    variant = code + suffix
                    if variant in MINISTRY_MAJORS:
                        format_issues.append({
                            'db_item': m,
                            'correct_code': variant,
                            'correct_name': MINISTRY_MAJORS[variant]
                        })
                        break
    if format_issues:
        print(f"  发现 {len(format_issues)} 个代码格式不匹配，需要先删除再补充：")
        # 删除格式错误的，之后补充正确的
        for issue in format_issues[:]:
            print(f"    {issue['db_item']['code']} → 应为 {issue['correct_code']} ({issue['correct_name']})")
            if delete_from_db(issue['db_item']['id']):
                codes_to_add.add(issue['correct_code'])
                format_issues.remove(issue)
            time.sleep(0.1)
    
    # 5. 补充缺失的清单专业
    if codes_to_add:
        print(f"\n[步骤5] 补充教育部清单中的 {len(codes_to_add)} 个专业...")
        added_count = 0
        skipped_count = 0
        for code in sorted(codes_to_add):
            name = MINISTRY_MAJORS[code]
            major_data = create_major_data(code, name)
            result = insert_to_db(major_data)
            if result == True:
                print(f"  ✅ 添加: {code} - {name}")
                added_count += 1
            elif result == "exists":
                print(f"  ⏭️ 已存在: {code} - {name}")
                skipped_count += 1
            else:
                print(f"  ❌ 失败: {code} - {name}")
            time.sleep(0.1)
        print(f"\n  补充完成: 新增 {added_count} 个，已存在 {skipped_count} 个")
    
    # 6. 最终统计
    print("\n[步骤6] 最终验证...")
    final_majors = fetch_all_from_db()
    final_codes = {m['code'] for m in final_majors}
    missing = ministry_codes - final_codes
    extra = final_codes - ministry_codes
    
    print("\n" + "="*80)
    print("最终结果")
    print("="*80)
    print(f"  数据库专业总数: {len(final_majors)}")
    print(f"  覆盖清单专业: {len(ministry_codes & final_codes)} / {len(ministry_codes)} ({(len(ministry_codes & final_codes)/len(ministry_codes)*100):.1f}%)")
    if missing:
        print(f"  仍缺失的专业数: {len(missing)}")
        for code in sorted(missing)[:10]:
            print(f"    - {code} {MINISTRY_MAJORS[code]}")
        if len(missing) > 10:
            print(f"    ...还有 {len(missing)-10} 个")
    if extra:
        print(f"  仍然超出清单的专业数: {len(extra)}")
        for code in sorted(extra):
            print(f"    - {code}")
    print("\n处理完成！")
